#!/usr/bin/env python3
"""Generate runtime language metadata/catalogs and engine choices from one registry."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def load_registry(path):
    entries = json.loads(path.read_text(encoding='utf-8'))
    if not isinstance(entries, list) or not entries:
        raise ValueError('The language registry must be a nonempty list')
    codes = set()
    for entry in entries:
        code = entry.get('code', '')
        if not isinstance(code, str) or not re.fullmatch(r'[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*', code) or len(code) > 35 or code in codes:
            raise ValueError('Invalid or duplicated product language code: ' + str(code))
        codes.add(code)
        for key in ('name', 'native_locale', 'engine_locale', 'catalog'):
            if not isinstance(entry.get(key), str) or not entry[key] or any(c in entry[key] for c in '\0\n\r'):
                raise ValueError('Invalid language metadata: ' + key)
        if not isinstance(entry.get('incomplete'), bool):
            raise ValueError('Language completeness must be explicit')
        catalog = Path(entry['catalog'])
        if catalog.is_absolute() or '..' in catalog.parts:
            raise ValueError('Catalog must be relative to the registry')
    if 'en' not in codes:
        raise ValueError('The English fallback is required')
    return entries


def products(registry, output):
    entries = load_registry(registry)
    literal = lambda value: json.dumps(value, ensure_ascii=False)
    header = ['// Generated by tools/generate_product_languages.py; edit localization/ instead.',
              '#pragma once', '#include <string>', '#include <string_view>', '#include <unordered_map>',
              'namespace cwm {',
              'struct ProductLanguageDefinition { const char *code, *name, *native_locale, *engine_locale; bool incomplete; };',
              'inline const ProductLanguageDefinition *product_language(const std::string_view code);',
              'inline const auto &product_languages() {', '    static const ProductLanguageDefinition values[] = {']
    for e in entries:
        header.append('        {' + ', '.join(literal(e[k]) for k in ('code','name','native_locale','engine_locale')) + ', ' + str(e['incomplete']).lower() + '},')
    header.extend(['    }; return values;', '}',
                   'inline const ProductLanguageDefinition *product_language(const std::string_view code) {',
                   '    for (const auto &value : product_languages()) if (code == value.code) return &value;',
                   '    return nullptr;', '}',
                   'inline const char *catalog_translation(const std::string &code, const char *english) {',
                   '    static const std::unordered_map<std::string, std::unordered_map<std::string, std::string>> catalogs{'])
    for e in entries:
        strings = json.loads((registry.parent / e['catalog']).read_text(encoding='utf-8'))
        if not isinstance(strings, dict) or any(not isinstance(v,str) or '\0' in k or '\0' in v for k,v in strings.items()):
            raise ValueError('Catalog must map English messages to translated strings')
        header.append('        {' + literal(e['code']) + ', {')
        for key,value in sorted(strings.items()):
            if value:
                header.append('            {' + literal(key) + ', ' + literal(value) + '},')
        header.append('        }},')
    header.extend(['    };', '    const auto catalog = catalogs.find(code);',
                   '    if (catalog == catalogs.end()) return nullptr;',
                   '    const auto message = catalog->second.find(english);',
                   '    return message == catalog->second.end() ? nullptr : message->second.c_str();', '}', '} // namespace cwm', ''])
    lua = ['-- Generated by tools/generate_product_languages.py; edit localization/ instead.', 'return {']
    for e in entries:
        lua.append('    [' + literal(e['code']) + '] = ' + literal(e['name'] + (' (WIP)' if e['incomplete'] else '')) + ',')
    lua.extend(['}', ''])
    setting = output/'luanti/builtin/settingtypes.txt'
    old = setting.read_text() if setting.exists() else 'cwm_language (Language) enum en en,it\n'
    new = re.sub(r'^cwm_language \(Language\) enum .+$', 'cwm_language (Language) enum en ' + ','.join(e['code'] for e in entries), old, flags=re.M)
    if new == old and not re.search(r'^cwm_language ', old, re.M):
        raise ValueError('Missing product setting definition')
    return {
        output/'protocol/include/cwm/product_languages_generated.hpp':'\n'.join(header),
        output/'luanti/builtin/mainmenu/settings/product_languages.lua':'\n'.join(lua),
        setting:new,
    }


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--registry',type=Path,default=ROOT/'localization/languages.json')
    parser.add_argument('--output-root',type=Path,default=ROOT)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    for path, content in products(args.registry,args.output_root).items():
        if args.check:
            if not path.is_file() or path.read_text()!=content:
                raise SystemExit('Stale generated product language file: '+str(path))
        else:
            path.parent.mkdir(parents=True,exist_ok=True);path.write_text(content,encoding='utf-8')


if __name__=='__main__': main()
