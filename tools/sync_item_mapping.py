#!/usr/bin/env python3
from pathlib import Path
import csv, hashlib, json, re, shutil

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "artifacts/item-mapping"
B = D / "sol-pass1-batches"
MOD = ROOT / "game/mods/cdda_items"
TEX = MOD / "textures"

def fnv64(s):
    h = 14695981039346656037
    for b in s.encode("utf-8"):
        h ^= b
        h = (h * 1099511628211) & 0xffffffffffffffff
    return f"{h:016x}"

def atom(path, text):
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.replace(path)

with (D/"mineclonia-items.tsv").open(newline="", encoding="utf-8") as f:
    catalog = {r["id"]: r for r in csv.DictReader(f, delimiter="\t")}

outputs = sorted(B.glob("batch-[0-9][0-9][0-9][0-9]-output.json"))
records = {}

for op in outputs:
    ip = op.with_name(op.name.replace("-output.json", ".json"))
    if not ip.exists():
        raise RuntimeError(f"missing input for {op.name}: {ip.name}")
    inp = json.loads(ip.read_text(encoding="utf-8"))
    out = json.loads(op.read_text(encoding="utf-8"))
    if len(inp) != len(out):
        raise RuntimeError(f"{op.name}: {len(inp)} inputs != {len(out)} outputs")

    for a, r in zip(inp, out):
        cid = a["cdda_id"]
        if r.get("cdda_id") != cid:
            raise RuntimeError(f"{op.name}: expected {cid}, got {r.get('cdda_id')}")
        allowed = {c["mineclonia_id"] for c in a["candidates"]}
        best = r.get("best_mineclonia_id")
        if r.get("decision") == "NO_GOOD_MATCH":
            if best is not None:
                raise RuntimeError(f"{op.name}: {cid}: NO_GOOD_MATCH with best")
        elif best not in allowed:
            raise RuntimeError(f"{op.name}: {cid}: invalid best {best}")
        if cid in records and records[cid] != r:
            raise RuntimeError(f"conflicting production mappings for {cid}")
        records[cid] = dict(r, provenance=op.name)

# Resolve Mineclonia texture filenames globally.
tex_index = {}
for p in (ROOT/"mineclonia").rglob("*.png"):
    tex_index.setdefault(p.name, []).append(p)

def copy_texture(name):
    matches = tex_index.get(name, [])
    if not matches:
        raise RuntimeError(f"Mineclonia texture not found: {name}")
    hashes = {hashlib.sha256(p.read_bytes()).hexdigest() for p in matches}
    if len(hashes) != 1:
        raise RuntimeError(f"ambiguous Mineclonia texture basename: {name}")
    TEX.mkdir(parents=True, exist_ok=True)
    shutil.copy2(matches[0], TEX/name)
    return matches[0]

master = []
lua = [
    "-- Generated by tools/sync_item_mapping.py. Do not edit.",
    "",
]
assets = []
supported = unsupported = no_match = 0
seen_runtime_names = {}

for cid in sorted(records):
    r = records[cid]
    mid = r.get("best_mineclonia_id")
    presentation = "fallback"

    if mid:
        m = catalog.get(mid)
        if not m:
            raise RuntimeError(f"{cid}: Mineclonia id absent from catalog: {mid}")

        image = m.get("inventory_image") or m.get("wield_image") or ""
        pngs = re.findall(r"([A-Za-z0-9_.-]+\.png)", image)

        if m.get("type") in {"craftitem", "tool"} and image and pngs:
            runtime = "cdda_items:i_" + fnv64(cid)
            old = seen_runtime_names.setdefault(runtime, cid)
            if old != cid:
                raise RuntimeError(f"runtime-name collision: {old} / {cid}")

            for png in sorted(set(pngs)):
                src = copy_texture(png)
                assets.append((png, str(src.relative_to(ROOT)),
                               hashlib.sha256(src.read_bytes()).hexdigest()))

            qcid = json.dumps(cid, ensure_ascii=False)
            qrun = json.dumps(runtime)
            qdesc = json.dumps(f"CDDA visual: {cid}", ensure_ascii=False)
            qimg = json.dumps(image)
            lua += [
                f"minetest.register_craftitem({qrun}, {{",
                f"    description = {qdesc},",
                f"    inventory_image = {qimg},",
                "    stack_max = 1,",
                "    groups = {not_in_creative_inventory = 1},",
                "})",
                f"cdda_items.visual_by_cdda_id[{qcid}] = {qrun}",
                "",
            ]
            presentation = runtime
            supported += 1
        else:
            unsupported += 1
    else:
        no_match += 1

    master.append({
        "cdda_id": cid,
        "mineclonia_id": mid or "",
        "decision": r["decision"],
        "confidence": r["confidence"],
        "visual_family": r["visual_family"],
        "procedural_variant": str(bool(r["procedural_variant_recommended"])).lower(),
        "presentation_item": presentation,
        "provenance": r["provenance"],
        "reason": r["reason"],
    })

fields = list(master[0]) if master else [
    "cdda_id","mineclonia_id","decision","confidence","visual_family",
    "procedural_variant","presentation_item","provenance","reason"
]
with (D/"master-item-mapping.tsv").open("w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=fields, delimiter="\t")
    w.writeheader(); w.writerows(master)
atom(D/"master-item-mapping.json",
     json.dumps(master, ensure_ascii=False, indent=2) + "\n")
atom(MOD/"generated_mapping.lua", "\n".join(lua) + "\n")

asset_rows = sorted(set(assets))
# Retain upstream attribution alongside the copied presentation media.
notices = MOD / "media-notices"
notices.mkdir(parents=True, exist_ok=True)
for filename in ("LEGAL.md", "LICENSE.txt", "CREDITS.md"):
    shutil.copy2(ROOT / "mineclonia" / filename, notices / ("Mineclonia-" + filename))
for source_mod in sorted({(ROOT / source).parent.parent for _, source, _ in asset_rows}):
    for source in sorted(source_mod.iterdir()):
        if source.is_file() and any(word in source.name.lower()
                for word in ("readme", "license", "copying", "credit", "author")):
            shutil.copy2(source, notices / (source_mod.name + "-" + source.name))
with (MOD/"generated_assets.tsv").open("w", newline="", encoding="utf-8") as f:
    w = csv.writer(f, delimiter="\t")
    w.writerow(["texture","source","sha256"])
    w.writerows(asset_rows)

report = {
    "production_batches": len(outputs), "records": len(master),
    "presentation_supported": supported,
    "mapped_but_fallback": unsupported, "no_good_match": no_match,
    "copied_textures": len(asset_rows),
}
atom(D/"sync-report.json", json.dumps(report, indent=2) + "\n")
atom(MOD/"mapping_provenance.json", json.dumps({
    "mineclonia_pin": json.loads((ROOT / "baseline/manifest.json").read_text())["repositories"]["mineclonia"]["commit"],
    "report": report,
    "production_outputs": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in outputs},
}, indent=2) + "\n")
print(json.dumps(report, indent=2))
